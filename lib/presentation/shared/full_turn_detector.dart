import 'dart:math' as math;

/// Считает полные обороты внутри одного непрерывного движения по крутилке.
///
/// Отдельный класс, а не пара полей в состоянии виджета, ровно по одной
/// причине: здесь легко ошибиться незаметно. «Оборот» — это накопленный
/// поворот в одну сторону за один жест, а не сумма модулей: покрутив
/// туда-сюда на полкруга, человек оборота не сделал, и считать это оборотом
/// значило бы срабатывать на обычной подкрутке времени.
///
/// На саму крутилку класс не влияет: минуты считаются той же дельтой, что и
/// раньше, а это — независимый наблюдатель поверх того же потока событий.
class FullTurnDetector {
  /// Накопленный поворот с начала жеста, в радианах. Знак значим.
  double _turned = 0;

  /// Сколько полных оборотов уже отмечено в этом жесте.
  int _reported = 0;

  /// Начало нового движения. Всё накопленное прошлым жестом обнуляется:
  /// оборот «по частям», с отрывом пальца, оборотом не считается.
  void start() {
    _turned = 0;
    _reported = 0;
  }

  void end() => start();

  /// Добавляет очередную угловую дельту (в радианах, уже нормализованную
  /// через ±pi) и отвечает, замкнулся ли на ней полный круг.
  bool add(double delta) {
    _turned += delta;
    final turns = _turned.abs() ~/ (2 * math.pi);
    final crossed = turns > _reported;
    // Присваивается всегда, в том числе вниз: если человек отмотал назад и
    // пошёл в другую сторону, следующий полный круг — тоже полный круг.
    _reported = turns;
    return crossed;
  }

  /// Доля текущего оборота, 0..1 — для отладки и тестов.
  double get progress => (_turned.abs() % (2 * math.pi)) / (2 * math.pi);
}

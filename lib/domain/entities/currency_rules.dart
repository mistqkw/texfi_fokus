/// Правила внутриигровой валюты.
///
/// Отдельно от [GameRules] намеренно: валюта начисляется за сам факт
/// доведённой до конца фокус-сессии, независимо от того, включён ли игровой
/// режим с картой и противниками. Это разные системы поощрения на разных
/// событиях, и смешивать их в одном месте значило бы однажды не суметь
/// поменять одно, не задев другое.
abstract final class CurrencyRules {
  /// Награда за одну успешно завершённую (не прерванную и не сорванную)
  /// фокус-сессию.
  ///
  /// Единственное число, которое трогают, чтобы изменить темп заработка, —
  /// поэтому оно и вынесено отдельной именованной константой, а не вписано
  /// числом прямо в место начисления.
  static const int sessionReward = 10;
}
